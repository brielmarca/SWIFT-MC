export type RegulationBlock = { id: string; ruleId?: string; paragraphs: string[] };
export type RegulationSection = { id: string; title: string; blocks: RegulationBlock[] };

function regulation(id: string, label: string, text: string) {
  const paragraphs = text.split("\n\n");
  const title = paragraphs.shift()!;
  const closing = paragraphs.splice(-2);
  const introduction: string[] = [];
  const sections: RegulationSection[] = [];
  for (const paragraph of paragraphs) {
    const sectionNumber = paragraph.match(/^§(\d+) — /)?.[1];
    if (sectionNumber) {
      sections.push({ id: `${id}-section-${sectionNumber}`, title: paragraph, blocks: [] });
      continue;
    }
    const section = sections.at(-1);
    if (!section) { introduction.push(paragraph); continue; }
    const ruleId = paragraph.match(/^(\d+\.\d+)\. /)?.[1];
    if (ruleId || !section.blocks.length) {
      section.blocks.push({ id: ruleId ? `${id}-${ruleId}` : `${section.id}-text`, ruleId, paragraphs: [] });
    }
    section.blocks.at(-1)!.paragraphs.push(paragraph);
  }
  return { id, label, title, introduction, sections, closing };
}

