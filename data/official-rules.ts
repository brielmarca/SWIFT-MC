export function filterRuleSections(sections: RegulationSection[], query: string) {
  const normalize = (value: string) => value.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLocaleLowerCase("pt-BR");
  const words = normalize(query).trim().split(/\s+/).filter(Boolean);
  return sections.map((section) => ({ ...section, blocks: section.blocks.filter((block) =>
    words.every((word) => normalize(`${section.title} ${block.paragraphs.join(" ")}`).includes(word)),
  ) })).filter((section) => section.blocks.length);
}
